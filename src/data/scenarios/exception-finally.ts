function ex(
  typeName: string,
  message: string,
  phase: "throwing" | "unwinding" | "caught",
  catchMethod?: string,
) {
  return {
    exceptionFlow: {
      typeName,
      message,
      phase,
      ...(catchMethod ? { catchMethod } : {}),
    },
  };
}

